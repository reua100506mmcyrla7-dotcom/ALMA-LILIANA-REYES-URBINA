#OPERADORES MATEMATICOS(ARITMETICOS)
a=10
b=2.5
#1. SUMA(+)
print("El resultado de suma es:",a+b)
#2. RESTA(-)
print("El resultado de la resta es:",a-b)
#3. MULTIPLICACION(*)
print("El resultado de multiplicacion es:",a*b)
#4 DIVISION(*)
print("El resultado de division es:",a/b)
#5. MODULO(%)
print("El resultado de modulo es:",a%b)